% PREPROCESSPIPELINE_CONFIG Configuration templates for preprocessPipeline
%
% This file contains example configuration structures for common preprocessing
% workflows using dwim.preprocessPipeline().

%% Basic 2D Image Processing
config_2d_basic = struct(...
    'inputType', 'filepath', ...
    'outputType', 'image', ...
    'steps', {{'validate', 'window', 'normalize'}}, ...
    'parameters', struct(...
        'window', struct('preset', 'lung'), ...
        'validate', struct() ...
    ), ...
    'validation', struct('enabled', true), ...
    'verbose', true ...
);

%% 3D Volume from DICOM Directory
config_3d_volume = struct(...
    'inputType', 'dicomdir', ...
    'outputType', 'volume', ...
    'steps', {{'orient', 'resample', 'validate_volume'}}, ...
    'parameters', struct(...
        'orient', struct('targetOrientation', 'RAS'), ...
        'resample', struct('targetSpacing', 1.0), ...
        'validate_volume', struct() ...
    ), ...
    'validation', struct('enabled', true), ...
    'verbose', true ...
);

%% Full Pipeline (DICOM → Processed Volume)
config_full_pipeline = struct(...
    'inputType', 'dicomdir', ...
    'outputType', 'volume', ...
    'steps', {{'orient', 'normalize', 'window', 'resample', 'validate_volume'}}, ...
    'parameters', struct(...
        'orient', struct('targetOrientation', 'RAS'), ...
        'normalize', struct(), ...
        'window', struct('preset', 'lung'), ...
        'resample', struct('targetSpacing', 1.0), ...
        'validate_volume', struct() ...
    ), ...
    'validation', struct('enabled', true), ...
    'verbose', true ...
);

%% Minimal Processing
config_minimal = struct(...
    'inputType', 'image', ...
    'outputType', 'image', ...
    'steps', {{}}, ...  % No processing steps
    'parameters', struct(), ...
    'validation', struct('enabled', false), ...
    'verbose', false ...
);

%% Custom Research Pipeline
config_research = struct(...
    'inputType', 'volume', ...
    'outputType', 'volume', ...
    'steps', {{'resample', 'validate_volume'}}, ...
    'parameters', struct(...
        'resample', struct('targetSpacing', 0.5), ...  % High resolution
        'validate_volume', struct('MinSlices', 50) ...  % Stricter validation
    ), ...
    'validation', struct('enabled', true), ...
    'verbose', true ...
);

